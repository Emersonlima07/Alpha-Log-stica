_database_url = config("DATABASE_URL", default="")

if _database_url.startswith("postgres"):
    import re

    m = re.match(
        r"postgres(?:ql)?://(?P<user>[^:]+):(?P<password>[^@]+)@(?P<host>[^:/]+):?(?P<port>\d*)/(?P<name>.+)",
        _database_url,
    )
    if not m:
        raise ValueError("DATABASE_URL invalida. Use o formato postgres://user:pass@host:port/db")
    d = m.groupdict()
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": d["name"],
            "USER": d["user"],
            "PASSWORD": d["password"],
            "HOST": d["host"],
            "PORT": d["port"] or "5432",
        }
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

